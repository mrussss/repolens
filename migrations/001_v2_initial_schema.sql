CREATE TABLE IF NOT EXISTS repositories (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    name VARCHAR(128) NOT NULL,
    git_url VARCHAR(512) NOT NULL,
    default_ref VARCHAR(128) NOT NULL DEFAULT 'main',
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    UNIQUE KEY uq_repository_git_url (git_url),
    KEY idx_repo_user_status_created (user_id, status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS repository_snapshots (
    id VARCHAR(64) PRIMARY KEY,
    repository_id VARCHAR(64) NOT NULL,
    commit_sha VARCHAR(64) NOT NULL,
    ref VARCHAR(128) NOT NULL,
    requested_ref VARCHAR(128) NULL,
    materialized_path VARCHAR(512) NOT NULL,
    content_hash VARCHAR(64) NOT NULL DEFAULT '',
    status VARCHAR(32) NOT NULL DEFAULT 'CREATED',
    file_count INT NOT NULL DEFAULT 0,
    total_bytes BIGINT NOT NULL DEFAULT 0,
    error_code VARCHAR(64) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    ready_at DATETIME(3) NULL,
    UNIQUE KEY uq_snapshot_repo_commit (repository_id, commit_sha),
    KEY idx_snapshot_repo_status_created (repository_id, status, created_at),
    CONSTRAINT chk_snapshot_status CHECK (status IN ('CREATED', 'MATERIALIZING', 'READY', 'FAILED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

