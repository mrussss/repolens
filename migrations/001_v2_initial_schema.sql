    symbol_schema_version VARCHAR(32) NOT NULL,
    build_context_hash VARCHAR(64) NOT NULL,
    module_path VARCHAR(255) NOT NULL,
    goos VARCHAR(32) NOT NULL DEFAULT 'linux',
    goarch VARCHAR(32) NOT NULL DEFAULT 'amd64',
    build_tags_hash VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'CREATED',
    files_total INT NOT NULL DEFAULT 0,
    files_parsed INT NOT NULL DEFAULT 0,
    files_failed INT NOT NULL DEFAULT 0,
    packages_total INT NOT NULL DEFAULT 0,
    packages_typechecked INT NOT NULL DEFAULT 0,
    packages_failed INT NOT NULL DEFAULT 0,
    symbol_count INT NOT NULL DEFAULT 0,
    semantic_relation_count INT NOT NULL DEFAULT 0,
    syntactic_relation_count INT NOT NULL DEFAULT 0,
    heuristic_relation_count INT NOT NULL DEFAULT 0,
