CREATE TABLE IF NOT EXISTS code_files (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    code_index_build_id BIGINT NOT NULL,
    path VARCHAR(512) NOT NULL,
    package_path VARCHAR(255) NOT NULL,
    package_name VARCHAR(128) NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    line_count INT NOT NULL DEFAULT 0,
    size_bytes BIGINT NOT NULL DEFAULT 0,
    is_test BOOLEAN NOT NULL DEFAULT FALSE,
    included_by_build_context BOOLEAN NOT NULL DEFAULT TRUE,
    parse_status VARCHAR(32) NOT NULL DEFAULT 'OK',
    parse_error TEXT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    KEY idx_file_build_path (code_index_build_id, path)
