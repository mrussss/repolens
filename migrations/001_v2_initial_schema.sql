CREATE TABLE IF NOT EXISTS symbols (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    code_index_build_id BIGINT NOT NULL,
    file_id BIGINT NOT NULL,
    file_path VARCHAR(512) NOT NULL,
    symbol_key_raw VARCHAR(512) NOT NULL,
    symbol_key_hash VARCHAR(64) NOT NULL,
    module_path VARCHAR(255) NOT NULL,
    package_path VARCHAR(255) NOT NULL,
    package_name VARCHAR(128) NOT NULL,
    kind VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    qualified_name VARCHAR(255) NOT NULL,
    receiver_raw VARCHAR(128) NULL,
    receiver_canonical VARCHAR(128) NULL,
    signature TEXT NULL,
    doc TEXT NULL,
    start_line INT NOT NULL,
    start_col INT NOT NULL,
    end_line INT NOT NULL,
    end_col INT NOT NULL,
    exported BOOLEAN NOT NULL DEFAULT FALSE,
    content_hash VARCHAR(64) NOT NULL,
